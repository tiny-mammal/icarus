import type { Plugin } from 'vite';
import { repoAssets } from './repo-assets';

/**
 * Makes the browser build of the diary installable: a web app manifest, its
 * icons, the Apple tags iOS and macOS Safari read, and a service worker that
 * keeps every file of the build cached so the installed app opens offline.
 *
 * Paths are relative to Vite's `base`, so the same output works at `/app/` on
 * icarus.4oli.com and at `/` in the Tauri build (which never registers the
 * worker; see `src/lib/install.svelte.ts`).
 */

const ICONS = {
  'icon-192.png': 'src-tauri/icons/android/mipmap-xxxhdpi/ic_launcher.png',
  'icon-512.png': 'src-tauri/icons/icon.png',
  'apple-touch-icon.png': 'src-tauri/icons/ios/AppIcon-60x60@3x.png',
};

const MANIFEST = {
  id: './',
  name: 'Icarus Diary',
  short_name: 'Icarus',
  description: 'A private, open-source diary. Your entries stay on this device.',
  start_url: './',
  scope: './',
  display: 'standalone',
  background_color: '#09090b',
  theme_color: '#09090b',
  icons: [
    { src: 'icon-192.png', sizes: '192x192', type: 'image/png' },
    { src: 'icon-512.png', sizes: '512x512', type: 'image/png' },
    // Full-bleed, with the mark well inside the safe zone.
    { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
};

/** Files from `public/` that the app loads; Vite copies them without listing them in the bundle. */
const PUBLIC_FILES = ['favicon.svg'];

/**
 * The service worker. Pages come from the network first, so an update shows up
 * on the next visit, with the cached copy as the fallback when the network
 * fails or the server answers with an error. Everything else is a hashed build
 * file and comes from the cache first. It never touches other origins (the app
 * makes no such requests anyway).
 *
 * A new version waits until every tab of the old one has closed before it
 * takes over and deletes the old cache: an open tab can still lazy-load a
 * chunk of its own build (the editor, for one), which the new deployment no
 * longer serves.
 */
function serviceWorker(version: string, files: string[]): string {
  return `// Generated by vite/pwa.ts.
const CACHE = 'icarus-${version}';
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(FILES)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith('icarus-') && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    const cached = () => caches.match('./', { ignoreSearch: true });
    event.respondWith(
      fetch(request)
        .then((response) => (response.ok ? response : cached().then((page) => page || response)))
        .catch(cached),
    );
    return;
  }
  event.respondWith(caches.match(request).then((hit) => hit || fetch(request)));
});
`;
}

export function pwa(): Plugin[] {
  let base = '/';
  const manifest = JSON.stringify(MANIFEST, null, 2);
  return [
    repoAssets('icarus-pwa-icons', { ...ICONS }),
    {
      name: 'icarus-pwa',
      configResolved(config) {
        base = config.base;
      },
      configureServer(server) {
        server.middlewares.use((req, res, next) => {
          if ((req.url ?? '').split('?')[0] !== `${base}manifest.webmanifest`) return next();
          res.setHeader('Content-Type', 'application/manifest+json');
          res.end(manifest);
        });
      },
      transformIndexHtml() {
        return [
          { tag: 'link', attrs: { rel: 'manifest', href: `${base}manifest.webmanifest` }, injectTo: 'head' },
          { tag: 'link', attrs: { rel: 'apple-touch-icon', href: `${base}apple-touch-icon.png` }, injectTo: 'head' },
          { tag: 'meta', attrs: { name: 'apple-mobile-web-app-title', content: 'Icarus' }, injectTo: 'head' },
          // The app bar is not padded for a translucent status bar, so keep it opaque.
          { tag: 'meta', attrs: { name: 'apple-mobile-web-app-status-bar-style', content: 'black' }, injectTo: 'head' },
          { tag: 'meta', attrs: { name: 'mobile-web-app-capable', content: 'yes' }, injectTo: 'head' },
        ];
      },
      generateBundle: {
        // After the HTML is emitted, so the page itself is cached too.
        order: 'post',
        handler(_options, bundle) {
          this.emitFile({ type: 'asset', fileName: 'manifest.webmanifest', source: manifest });
          const built = Object.keys(bundle).filter((file) => !file.endsWith('.map'));
          const files = [
            './',
            'manifest.webmanifest',
            ...PUBLIC_FILES,
            ...Object.keys(ICONS),
            ...built.filter((file) => file !== 'index.html'),
          ];
          const version = Object.keys(bundle)
            .filter((file) => file.startsWith('assets/'))
            .sort()
            .join('')
            .split('')
            .reduce((hash, ch) => (Math.imul(hash, 31) + ch.charCodeAt(0)) | 0, 0);
          this.emitFile({
            type: 'asset',
            fileName: 'sw.js',
            source: serviceWorker((version >>> 0).toString(36), [...new Set(files)]),
          });
        },
      },
    },
  ];
}
